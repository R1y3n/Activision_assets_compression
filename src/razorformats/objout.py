"""Wavefront OBJ/MTL writer used as a simple open-format fallback."""

from __future__ import annotations

from pathlib import Path
from typing import Sequence


def write_obj(
    path: str | Path,
    name: str,
    positions: Sequence[Sequence[float]],
    indices: Sequence[int],
    uvs: Sequence[Sequence[float]] | None = None,
    normals: Sequence[Sequence[float]] | None = None,
    texture: str | Path | None = None,
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# exported by razor-openformats", f"o {name}"]
    if texture is not None:
        lines.append(f"mtllib {Path(texture).with_suffix('.mtl').name}")
    for x, y, z in positions:
        lines.append(f"v {x:.6f} {y:.6f} {z:.6f}")
    if uvs:
        for u, v in uvs:
            lines.append(f"vt {u:.6f} {v:.6f}")
    if normals:
        for x, y, z in normals:
            lines.append(f"vn {x:.6f} {y:.6f} {z:.6f}")
    if texture is not None:
        lines.append(f"usemtl {Path(texture).stem}")
    for i in range(0, len(indices), 3):
        face = indices[i:i + 3]
        if len(face) != 3:
            continue
        verts = []
        for idx in face:
            if uvs and normals:
                verts.append(f"{idx + 1}/{idx + 1}/{idx + 1}")
            elif uvs:
                verts.append(f"{idx + 1}/{idx + 1}")
            elif normals:
                verts.append(f"{idx + 1}//{idx + 1}")
            else:
                verts.append(str(idx + 1))
        lines.append("f " + " ".join(verts))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if texture is not None:
        mtl = path.with_suffix(".mtl")
        mtl.write_text(
            f"newmtl {Path(texture).stem}\n"
            "Ka 1.000 1.000 1.000\nKd 1.000 1.000 1.000\n"
            "illum 2\n"
            f"map_Kd {Path(texture).name}\n",
            encoding="utf-8")
    return path


def write_obj_scene(
    path: str | Path,
    meshes: Sequence[dict],
    textures: dict[str, str] | None = None,
) -> Path:
    """Write a multi-mesh BiN scene as one OBJ plus a matching MTL.

    `meshes` items use the shape produced by :mod:`razorformats.binfile`:
    ``name``, ``vertices`` (position/normal/uv), ``faces`` and ``shader``.
    `textures` optionally maps shader names to PNG filenames.
    """
    textures = textures or {}
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by razor-openformats from a BiN .obj scene"]
    if textures:
        lines.append(f"mtllib {path.stem}.mtl")
    vertex_base = 1
    used_materials: list[str] = []
    for mesh in meshes:
        shader = mesh.get("shader") or "material"
        if shader not in used_materials:
            used_materials.append(shader)
        lines.append(f"g {mesh.get('name') or 'mesh'}")
        lines.append(f"usemtl {shader}")
        for vertex in mesh["vertices"]:
            p, n, uv = vertex["position"], vertex["normal"], vertex["uv"]
            lines.append(f"v {p[0]:.6f} {p[1]:.6f} {p[2]:.6f}")
            lines.append(f"vt {uv[0]:.6f} {uv[1]:.6f}")
            lines.append(f"vn {n[0]:.6f} {n[1]:.6f} {n[2]:.6f}")
        for face in mesh["faces"]:
            refs = " ".join(f"{vertex_base + i}/{vertex_base + i}/{vertex_base + i}"
                            for i in face)
            lines.append(f"f {refs}")
        vertex_base += len(mesh["vertices"])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if textures:
        mtl = [f"# Materials for {path.name}"]
        for shader, image in textures.items():
            mtl.extend([f"newmtl {shader}",
                        "Ka 1.000 1.000 1.000", "Kd 1.000 1.000 1.000",
                        "illum 2", f"map_Kd {Path(image).as_posix()}", ""])
        path.with_suffix(".mtl").write_text("\n".join(mtl) + "\n",
                                            encoding="utf-8")
    return path
